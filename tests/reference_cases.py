#!/usr/bin/env python3
"""Regenerate fixtures from command semantics and independent Python arithmetic."""
import json
from pathlib import Path

CASES = Path(__file__).resolve().parent / "cases"
COLLATZ_REFERENCE = {
    1: (1, 1), 15: (18, 160), 25: (24, 88), 27: (112, 9232),
    97: (119, 9232), 837799: (525, 2974984576),
    2147483647: (451, 1235346792567892),
}


def collatz(start):
    values = [start]
    while values[-1] != 1:
        n = values[-1]
        values.append(n // 2 if n % 2 == 0 else 3 * n + 1)
    if start in COLLATZ_REFERENCE:
        assert (len(values), max(values)) == COLLATZ_REFERENCE[start]
    return values


def values(items):
    return [{"value": n} for n in items]


def rgb(red, green, blue):
    return {"red": red, "green": green, "blue": blue}


def ok(**kwargs):
    return {"ok": True, **kwargs}


def error(code):
    return {"ok": False, "error": code}


def write(name, steps, flags=""):
    CASES.mkdir(exist_ok=True)
    prefix = f"#!args {flags}\n" if flags else ""
    (CASES / f"{name}.in").write_text(prefix + "\n".join(c for c, _ in steps) + "\n")
    (CASES / f"{name}.expected.json").write_text(json.dumps([e for _, e in steps], indent=2) + "\n")


def main():
    for start in COLLATZ_REFERENCE:
        collatz(start)
    header = ["/* Generated by reference_cases.py using independent Python integer arithmetic. */",
              "#ifndef TEST_REFERENCE_COLLATZ_H", "#define TEST_REFERENCE_COLLATZ_H"]
    for start in COLLATZ_REFERENCE:
        seq = collatz(start)
        header.append(f"static const unsigned long long sequence_{start}[] = {{")
        for i in range(0, len(seq), 8):
            header.append("    " + ", ".join(f"{n}ULL" for n in seq[i:i+8]) + ",")
        header.append("};")
    header.append("struct collatz_reference { int input; size_t terms; unsigned long long peak; const unsigned long long *values; };")
    header.append("static const struct collatz_reference references[] = {")
    for start, (terms, peak) in COLLATZ_REFERENCE.items():
        header.append(f"    {{{start}, {terms}, {peak}ULL, sequence_{start}}},")
    header.extend(["};", "#endif", ""])
    (CASES.parent / "reference_collatz.h").write_text("\n".join(header))
    write("book_example", [
        ("state", ok(counts={n: 0 for n in ("color", "collatz", "stack", "queue")})),
        ("color example", ok(counts={"color": 4}, contains={"color": rgb(138, 43, 226)}, effect_counts={"added": 4})),
        ("color traverse", ok(effect_indexes={"visited": {"structure": "color", "indexes": [0, 1, 2, 3]}})),
        ("check", ok()), ("color clear", ok(structures={"color": []}, effect_counts={"removed": 4})),
        ("reset", ok(counts={n: 0 for n in ("color", "collatz", "stack", "queue")})),
        ("help", ok()),
    ])
    a, b, c = rgb(1, 2, 3), rgb(4, 5, 6), rgb(1, 8, 9)
    write("color_operations", [
        ("color add_tail red=1 green=2 blue=3", ok(structures={"color": [a]})),
        ("color add_head red=4 green=5 blue=6", ok(structures={"color": [b, a]})),
        ("color insert index=0 red=1 green=8 blue=9", ok(structures={"color": [b, c, a]})),
        ("color search red=1", ok(structures={"color": [b, c, a]}, effect_indexes={"matched": {"structure": "color", "indexes": [1, 2]}})),
        ("color search red=255", error("E_NOT_FOUND")),
        ("color delete index=0", ok(structures={"color": [c, a]}, effect_indexes={"removed": {"structure": "color", "indexes": [0]}})),
        ("color delete red=1", ok(structures={"color": []}, effect_counts={"removed": 2})),
        ("color add_tail red=1 green=2 blue=3", ok(structures={"color": [a]})),
        ("color add_tail red=1 green=8 blue=9", ok(structures={"color": [a, c]})),
        ("color delete red=1 green=2", ok(structures={"color": [c]})),
        ("color clear", ok(structures={"color": []})),
    ])
    write("boundary_errors", [
        ("state", ok()),
        ("color delete index=0", error("E_RANGE")),
        *[(cmd, error("E_EMPTY")) for cmd in ("stack pop", "stack peek", "queue dequeue", "queue peek")],
        ("color insert index=0 red=1 green=2 blue=3", error("E_RANGE|E_EMPTY")),
        ("color add_tail red=1 green=2 blue=3", ok(structures={"color": [a]})),
        ("color insert index=9 red=1 green=2 blue=3", error("E_RANGE")),
        ("color insert index=-1 red=1 green=2 blue=3", error("E_RANGE")),
        ("color add_tail red=256 green=2 blue=3", error("E_RANGE")),
        ("color add_tail red=-1 green=2 blue=3", error("E_RANGE")),
        ("color add_tail red=abc green=2 blue=3", error("E_BAD_VALUE")),
        ("color add_tail red=1 green=2", error("E_MISSING_ARG")),
        ("color add_tail red=1 green=2 blue=3 red=4", error("E_SYNTAX|E_BAD_VALUE")),
        ("color add_tail red=1 green=2 blue=3 alpha=4", error("E_UNKNOWN_ARG")),
        ("color delete", error("E_MISSING_ARG")),
        ("color search", error("E_MISSING_ARG")),
        ("color delete index=0 red=1", error("E_SYNTAX|E_BAD_VALUE")),
        ("unknown command", error("E_UNKNOWN_CMD")),
        ("state" + " " * 507, ok()),
        ("state" + " " * 508, error("E_SYNTAX")),
        ("x" * 600, error("E_SYNTAX")),
        *[(f"collatz run start={n}", error("E_RANGE")) for n in (0, -1, 2147483648)],
        ("collatz run start=abc", error("E_BAD_VALUE")),
        ("collatz run", error("E_MISSING_ARG")),
        ("stack push value=9223372036854775808", error("E_RANGE|E_BAD_VALUE")),
        ("queue enqueue value=nan", error("E_BAD_VALUE")),
        ("state", ok(structures={"color": [a]})),
    ])
    write("stack_queue", [
        ("stack push value=10", ok(structures={"stack": values([10])})),
        ("stack push value=-2", ok(structures={"stack": values([-2, 10])})),
        ("stack push value=9223372036854775807", ok(structures={"stack": values([9223372036854775807, -2, 10])})),
        ("stack peek", ok(effect_indexes={"matched": {"structure": "stack", "indexes": [0]}})),
        ("stack pop", ok(structures={"stack": values([-2, 10])})),
        ("queue enqueue value=10", ok(structures={"queue": values([10])})),
        ("queue enqueue value=-2", ok(structures={"queue": values([10, -2])})),
        ("queue enqueue value=-9223372036854775808", ok(structures={"queue": values([10, -2, -9223372036854775808])})),
        ("queue peek", ok(effect_indexes={"matched": {"structure": "queue", "indexes": [0]}})),
        ("queue dequeue", ok(structures={"queue": values([-2, -9223372036854775808])})),
        ("reset", ok(counts={n: 0 for n in ("color", "collatz", "stack", "queue")})),
    ])
    write("max_nodes", [
        ("state", ok(max_nodes=3)),
        *[(f"stack push value={n}", ok(structures={"stack": values(list(range(n, 0, -1)))})) for n in (1, 2, 3)],
        ("stack push value=4", error("E_FULL")),
        ("color example", error("E_FULL")),
        ("collatz run start=15", error("E_FULL")),
        ("collatz run start=1", ok(structures={"collatz": values([1])})),
        ("collatz run start=25", error("E_FULL")),
        ("state", ok(structures={"collatz": values([1]), "stack": values([3, 2, 1])})),
    ], "--max-nodes 3")
    write("allocation_failure", [
        ("color add_tail red=1 green=2 blue=3", ok()),
        ("inject_fail after=0", ok()),
        ("color add_head red=4 green=5 blue=6", error("E_NOMEM")),
        ("inject_fail off", ok()),
        ("collatz run start=1", ok()),
        ("inject_fail after=3", ok()),
        ("collatz run start=25", error("E_NOMEM")),
        ("inject_fail off", ok()),
        ("state", ok(structures={"color": [a], "collatz": values([1])})),
        ("reset", ok()),
    ])
    seq27, seq837 = collatz(27), collatz(837799)
    write("collatz_reference", [
        *[(f"collatz run start={n}", ok(structures={"collatz": values(collatz(n))})) for n in (1, 15, 25, 97, 2147483647, 27)],
        ("collatz traverse", ok(effect_indexes={"visited": {"structure": "collatz", "indexes": list(range(len(seq27)))}})),
        ("collatz search value=9232", ok(effect_indexes={"matched": {"structure": "collatz", "indexes": [seq27.index(9232)]}})),
        ("collatz search value=99999", error("E_NOT_FOUND")),
        ("collatz delete value=9232", ok(structures={"collatz": values([n for n in seq27 if n != 9232])}, effect_counts={"removed": 1})),
        ("collatz run start=837799", ok(structures={"collatz": values(seq837)})),
        ("collatz search value=2974984576", ok(effect_counts={"matched": 1})),
        ("collatz delete value=2974984576", ok(structures={"collatz": values([n for n in seq837 if n != 2974984576])})),
        ("collatz clear", ok(structures={"collatz": []})),
    ])
    # Blank and comment lines have no replies, including whitespace-only lines.
    write("ignored_lines", [("state", ok()), ("check", ok())])
    path = CASES / "ignored_lines.in"
    path.write_text("\n# comment\n   \nstate\n\n# another\ncheck\n")
    print(f"Generated {len(list(CASES.glob('*.in')))} independent protocol fixtures")


if __name__ == "__main__":
    main()
